namespace PromptDot.Core.Settings;

/// <summary>
/// Defines the supported Prompter color themes.
/// </summary>
public enum PrompterTheme
{
    /// <summary>
    /// Near-black background with light text.
    /// </summary>
    StudioDark,

    /// <summary>
    /// Light background with dark text.
    /// </summary>
    StudioLight,

    /// <summary>
    /// Maximum-contrast presentation.
    /// </summary>
    HighContrast,
}
