namespace PromptDot.Core.Settings;

/// <summary>
/// Defines the supported Control window themes.
/// </summary>
public enum ApplicationTheme
{
    /// <summary>
    /// Follow the operating-system theme.
    /// </summary>
    System,

    /// <summary>
    /// Use the light application theme.
    /// </summary>
    Light,

    /// <summary>
    /// Use the dark application theme.
    /// </summary>
    Dark,
}
